<?php

declare(strict_types=1);

namespace App\Ai\Adaptation;

/**
 * Voice-ban scanner for adaptation artifacts.
 *
 * Runs inside the generate-validate-repair loop (GeneratesValidatedArtifact)
 * as a quality gate — the equivalent of the V2 Voice Lock Phase 8 audit.
 * It catches universal AI tells (em dashes, "something shifted", banned
 * vocabulary) on the same pass as structural validation so the repair
 * loop can re-generate before the artifact ships.
 *
 * This is a GATE, not an EDITOR — it refuses to ship bad output, it never
 * rewrites prose. The repair prompt tells the model what to fix and the
 * generator re-runs.
 *
 * IMPORTANT: This gate only catches UNIVERSAL AI tells — patterns that
 * appear when models imitate creative prose without authorial constraint,
 * regardless of the IP. Story-specific slop (a misnamed object in one
 * screenplay, a recurring body-language shorthand in another) is NOT
 * here. That belongs in the IP-specific bans generated by Voice Lock,
 * not in a global list. The root fix for story-specific slop is prompt
 * engineering: instructing the model to stay in the author's voice and
 * use the script's exact words. A deterministic word-list cannot catch
 * what the model will invent next; only the voice instruction can.
 *
 * Checks (exact match, no fuzzy style judgment):
 *   - Em dash character (—) and double-hyphen (--)
 *   - Semicolons in prose fields
 *   - Ellipses (...) in prose fields
 *   - Trailing "like a/an [noun]" similes in action lines
 *   - Banned vocabulary from the voice profile's universal + IP-specific bans
 *
 * Tolerance: a single soft-ban occurrence (trailing simile) logs a warning
 * but does not reject. Three or more soft-ban occurrences reject. Any
 * hard-ban occurrence rejects immediately.
 */
final class BannedProseValidator
{
    /**
     * Patterns that always reject — no tolerance.
     * Em dash in all variants, double-hyphen, semicolons, ellipses.
     */
    private const HARD_BAN_PATTERNS = [
        'em_dash' => '/\x{2014}|\x{2013}|\x{2015}/u',
        'double_hyphen' => '/--/',
        'semicolon' => '/;/',
        'ellipsis' => '/\.\.\./u',
    ];

    /**
     * Soft-ban pattern: trailing simile in action lines.
     * Tolerance: warn on 1-2, reject on 3+.
     */
    private const SIMILE_PATTERN = '/\blike\s+(?:a|an)\s+\w+/i';

    /**
     * Universal banned vocabulary — applies to every IP.
     * Supplemented by the voice profile's ip_specific_bans at runtime.
     */
    private const UNIVERSAL_BANNED_WORDS = [
        'tapestry', 'delve', 'underscore', 'highlight', 'showcase',
        'intricate', 'swift', 'meticulous', 'adept',
        'nestled', 'tucked away',
        'etch', 'etched',
    ];

    /**
     * Universal banned phrase-tells.
     *
     * These are TRULY universal AI writing tells — patterns that appear
     * when models imitate creative prose without authorial constraint.
     * They are never acceptable regardless of the IP or author.
     *
     * Story-specific slop (e.g., "jaw clenched" in one screenplay, a
     * misnamed object in another) is NOT here. That belongs in the
     * IP-specific bans generated by Voice Lock, not in a global list.
     */
    private const UNIVERSAL_BANNED_PHRASES = [
        'something shifted',
        'something clicked',
        'something broke',
        'breath they didn\'t know',
        'breath they didn’t know',
        'would later remember',
        'little did she know',
        'little did he know',
        'a reminder that',
        'a testament to',
        'it was clear that',
        'the kind of moment',
        'the kind of',
        'she couldn\'t quite',
        'she couldn’t quite',
        'he couldn\'t quite',
        'he couldn’t quite',
        'there was a quality to',
        'it occurred to her that',
        'it occurred to him that',
    ];

    /**
     * The universal bans in a form a prompt can state.
     *
     * @return array{punctuation: list<string>, words: list<string>, phrases: list<string>}
     */
    public static function universalBans(): array
    {
        return [
            'punctuation' => ['em dash and en dash', 'double hyphen (--)', 'semicolon', 'ellipsis (...)', 'three or more "like a/an" similes in one field'],
            'words' => self::UNIVERSAL_BANNED_WORDS,
            'phrases' => array_values(array_unique(array_map(
                static fn (string $phrase): string => str_replace('’', "'", $phrase),
                self::UNIVERSAL_BANNED_PHRASES,
            ))),
        ];
    }

    /**
     * Rewrite hard-ban punctuation into legal separators so a connective field
     * (next_bridge, why, a close hook) cannot brick Finalize over a semicolon.
     *
     * Vocabulary bans are not rewritten here — those still fail the scan.
     */
    public static function neutralizeBannedPunctuation(string $text): string
    {
        $text = preg_replace('/\x{2014}|\x{2013}|\x{2015}/u', ',', $text) ?? $text;
        $text = str_replace('--', ',', $text);
        $text = preg_replace_callback('/\s*;\s*(\p{Ll})?/u', static fn (array $match): string => '. '.mb_strtoupper($match[1] ?? ''), $text) ?? $text;
        $text = preg_replace('/\.{3,}/u', '.', $text) ?? $text;
        $text = preg_replace('/[ \t]+([.,])/u', '$1', $text) ?? $text;
        $text = preg_replace('/[ \t]{2,}/u', ' ', $text) ?? $text;

        return mb_trim($text);
    }

    /**
     * Scan prose fields in an artifact for banned patterns.
     *
     * @param  array<string, mixed>  $artifact  The generated artifact (draft or final cut)
     * @param  array<string, mixed>  $voiceProfile  Full voice profile with master_rule_1_hard_bans
     * @param  array<int, string>  $prosePaths  Dot-notation paths to prose fields to scan
     * @return array{errors: array<int, string>, warnings: array<int, string>}
     */
    public function scan(array $artifact, array $voiceProfile, array $prosePaths): array
    {
        $errors = [];
        $warnings = [];

        $ipBans = $this->extractIpBannedWords($voiceProfile);
        $bannedWords = array_unique(array_merge(self::UNIVERSAL_BANNED_WORDS, $ipBans['hard']));

        $proseValues = $this->extractProseValues($artifact, $prosePaths);

        foreach ($proseValues as $path => $text) {
            foreach (self::HARD_BAN_PATTERNS as $name => $pattern) {
                if (preg_match($pattern, $text)) {
                    $errors[] = "{$path}: banned {$name} found. Replace with a period, comma, or restructure the sentence.";
                }
            }

            foreach ($bannedWords as $word) {
                if (preg_match('/\b'.preg_quote($word, '/').'\b/i', $text)) {
                    $errors[] = "{$path}: banned vocabulary '{$word}'. Use the author's diction from the voice profile instead.";
                }
            }

            foreach ($ipBans['soft'] as $word) {
                if (preg_match('/\b'.preg_quote($word, '/').'\b/i', $text)) {
                    $warnings[] = "{$path}: IP-specific ban '{$word}' appears — verify it is the author's diction, not a shorthand.";
                }
            }

            foreach (self::UNIVERSAL_BANNED_PHRASES as $phrase) {
                if (mb_stripos($text, $phrase) !== false) {
                    $errors[] = "{$path}: banned phrase-tell '{$phrase}'. Rewrite in the author's voice.";
                }
            }

            $simileCount = preg_match_all(self::SIMILE_PATTERN, $text) ?: 0;
            if ($simileCount >= 3) {
                $errors[] = "{$path}: {$simileCount} trailing similes (like a/an ...). Replace with blunt concrete description.";
            } elseif ($simileCount >= 1) {
                $warnings[] = "{$path}: {$simileCount} trailing simile(s) — consider replacing with concrete description.";
            }
        }

        return ['errors' => $errors, 'warnings' => $warnings];
    }

    /**
     * Extract banned terms from the voice profile's IP-specific bans, split by how
     * safely each one can be enforced.
     *
     * The extraction reads a natural-language sentence written freely by Voice Lock,
     * so what comes out is unpredictable, and a multi-word phrase is a very different
     * risk from a bare word.
     *
     * A multi-word phrase targets a construction, so it is safe to reject on.
     *
     * A bare token is not. A ban phrased "Holmes in narration" yields "Holmes", and
     * "fog as atmosphere" yields "fog". Enforced as a hard error, either one fails
     * every draft in the title, on every attempt, with no possible repair, because the
     * narrator cannot write Baker Street without naming Holmes. Those still carry real
     * signal when the author genuinely overuses a word, so they are reported as
     * warnings and left for a human rather than allowed to brick a session.
     *
     * @param  array<string, mixed>  $voiceProfile
     * @return array{hard: array<int, string>, soft: array<int, string>}
     */
    private function extractIpBannedWords(array $voiceProfile): array
    {
        $hard = [];
        $soft = [];
        $ipBans = (array) data_get($voiceProfile, 'master_rule_1_hard_bans.ip_specific_bans', []);

        foreach ($ipBans as $ban) {
            if (! is_array($ban)) {
                continue;
            }

            $banText = (string) ($ban['ban'] ?? '');
            if ($banText === '') {
                continue;
            }

            // Extract the key noun/phrase from the ban text — the word itself, not the
            // full explanation. Heuristic: text before "in", "as", "for", or "when"
            // (e.g., "jaw in action lines" → "jaw").
            if (! preg_match('/^([^.!?]{2,40})\s+(?:in|as|for|when)\b/i', $banText, $m)) {
                continue;
            }

            $candidate = mb_trim($m[1]);

            if (mb_strlen($candidate) < 2 || mb_strlen($candidate) > 40 || $this->isInstructionFragment($candidate)) {
                continue;
            }

            if (preg_match('/\s/', $candidate) === 1) {
                $hard[] = $candidate;
            } else {
                $soft[] = $candidate;
            }
        }

        return ['hard' => array_unique($hard), 'soft' => array_unique($soft)];
    }

    /**
     * Whether an extracted candidate is an instruction fragment rather than a term.
     *
     * Voice Lock usually phrases bans as full sentences, so "Do not write grief as
     * overt sobbing monologue" yields "Do not write grief". As a literal term that is
     * inert, it will never appear in prose, but it is noise in every error message and
     * it hides the fact that the IP ban matched nothing.
     */
    private function isInstructionFragment(string $candidate): bool
    {
        return preg_match(
            '/^(?:do not|don\'t|do|avoid|never|no|refrain|stop|limit|reduce|minimi[sz]e)\b/i',
            $candidate,
        ) === 1;
    }

    /**
     * Extract prose values from an artifact by dot-notation paths.
     * Handles both scalar fields and arrays of strings. Expands `.*`
     * wildcards into concrete indices.
     *
     * @param  array<string, mixed>  $artifact
     * @param  array<int, string>  $paths
     * @return array<string, string>
     */
    private function extractProseValues(array $artifact, array $paths): array
    {
        $values = [];

        foreach ($paths as $path) {
            // Expand wildcards: "source_extracts.*" → "source_extracts.0", etc.
            if (str_contains($path, '.*')) {
                [$prefix, $suffix] = str_contains($path, '.*.')
                    ? explode('.*.', $path, 2)
                    : [mb_substr($path, 0, -2), ''];

                $collection = data_get($artifact, $prefix);

                if (! is_array($collection)) {
                    continue;
                }

                foreach (array_keys($collection) as $index) {
                    $subPath = $suffix !== ''
                        ? "{$prefix}.{$index}.{$suffix}"
                        : "{$prefix}.{$index}";
                    $value = data_get($artifact, $subPath);

                    if (is_string($value) && mb_trim($value) !== '') {
                        $values[$subPath] = $value;
                    }
                }

                continue;
            }

            $value = data_get($artifact, $path);

            if (is_string($value) && mb_trim($value) !== '') {
                $values[$path] = $value;
            } elseif (is_array($value)) {
                foreach ($value as $index => $item) {
                    if (is_string($item) && mb_trim($item) !== '') {
                        $values["{$path}.{$index}"] = $item;
                    }
                }
            }
        }

        return $values;
    }
}
